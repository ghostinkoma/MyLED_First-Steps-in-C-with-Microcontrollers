/*
 * ============================================================================
 *  MyLED.h  ―  複数 LED を「割り込みタイマー」で同時制御する学習用ライブラリ
 * ============================================================================
 *
 *  【このライブラリで学べること】
 *   1. クラス（class）の作り方 … LED 1個を LEDClass、全体の管理を LEDManager
 *   2. 配列とポインタ           … 複数の LED をまとめて扱う
 *   3. 演算子オーバーロード      … LED[0] のように「配列っぽく」書けるしくみ
 *   4. ハードウェアタイマー割り込み … loop() を止めずに一定間隔で処理する
 *   5. （発展）AVR のインラインアセンブラ … ポートを直接叩いて高速化する
 *
 *  【対応マイコン】
 *   - Arduino UNO / Nano 等（ATmega328P, 16MHz）… Timer1 + インラインアセンブラ
 *   - LGT8F328P                                  … 同上（AVR 互換）
 *   - ESP32 / ESP32-C3 / ESP32-S2 / ESP32-S3     … ハードウェアタイマー + digitalWrite
 *
 *  「マイコンごとの違い」は #if defined(...) で自動的に切り替わります。
 *  使う側（.ino）のコードは、どのマイコンでもまったく同じで動きます。
 * ============================================================================
 */

#ifndef MY_LED_H          // ← 同じヘッダを2回読み込んでも二重定義にならないための「インクルードガード」
#define MY_LED_H

#include <Arduino.h>      // pinMode / digitalWrite / uint8_t などの基本機能

/* ---------------------------------------------------------------------------
 *  LEDClass : LED「1個ぶん」を表すクラス
 *
 *  1個の LED について「どのピンか」「点滅させるか」「今つ点いているか」などの
 *  情報（状態）を自分で持ち、点ける／消す／点滅する、といった動作を提供します。
 * ------------------------------------------------------------------------- */
class LEDClass {
private:
    // ---- ピンに関する情報 ----
    uint8_t _pin;              // このLEDがつながっているピン番号

    // ---- AVR で「ポートを直接叩く」ための情報（ESP32では未使用）----
    volatile uint8_t* _port;   // 出力ポートレジスタのアドレス（例: &PORTB）
    uint8_t _bitmask;          // そのポート内でこのピンが占めるビット（例: 0x20）

    // ---- 点滅（トグル）の状態。割り込みの中で書き換わるので volatile を付ける ----
    volatile uint16_t _toggle_interval_ms; // 何ミリ秒ごとに反転するか（0=点滅しない）
    volatile uint16_t _timer_counter;      // 経過ミリ秒を数えるカウンタ
    volatile bool     _toggle_enabled;     // 点滅中かどうか
    volatile bool     _state;              // 今 HIGH(点灯) か LOW(消灯) か

public:
    LEDClass();                 // コンストラクタ（生成時に呼ばれる初期化）

    // 使うピンを登録して出力に設定する。最初に1回だけ呼ぶ
    void begin(uint8_t pin);

    // LED を点灯 / 消灯する（AVRではアセンブラ、それ以外は digitalWrite）
    void setHighInline();
    void setLowInline();

    // t ミリ秒ごとに点いたり消えたりを繰り返す。t=0 を渡すと点滅停止
    void toggle(int t);

    // 明るさを 0(消灯)〜255(全灯) の 256段階で指定（PWM）
    void pwm(uint8_t duty);

    // 【内部用】1ミリ秒ごとにタイマー割り込みから呼ばれる。ユーザーは呼ばない
    void _tick1ms();
};

/* ---------------------------------------------------------------------------
 *  LEDManager : 複数の LEDClass を「まとめて管理」するクラス
 *
 *  ・LED の配列を受け取って覚えておく
 *  ・LED[0] のように添字でアクセスできるようにする（operator[]）
 *  ・1msごとのタイマー割り込みを1つだけ立ち上げ、全LEDの _tick1ms() を呼ぶ
 *
 *  このクラスの実体（インスタンス）は下の extern 宣言のとおり LED という名前で
 *  1個だけ用意されています。ユーザーはそれを使います。
 * ------------------------------------------------------------------------- */
class LEDManager {
private:
    LEDClass* _leds;   // 管理する LED 配列の先頭アドレス
    size_t    _count;  // LED の個数

public:
    LEDManager();

    // 管理する LED 配列とその個数を登録し、タイマー割り込みを開始する
    void begin(LEDClass* ledArray, size_t count);

    // LED[n] という書き方を可能にする（添字演算子のオーバーロード）
    LEDClass& operator[](size_t index);

    // 【内部用】1msタイマーのセットアップ
    void initTimer1();

    // 【内部用】割り込みから呼ばれ、全LEDの _tick1ms() をまとめて呼ぶ
    void _tickAll();
};

// プログラム全体で共有する唯一の管理役。実体は MyLED.cpp にあります
extern LEDManager LED;

#endif // MY_LED_H
